public class Tabuada {
    public static void main(String[] args) {

        System.out.println("Tabuada");

        int num, cont, result;

        num = 5;
        cont = 1;

        while (cont <= 10) {

            result = num * cont;

            System.out.println("(Resultado: "+ result);
            cont++;
        }



    }
}
